import 'dublin_listing_builder.dart';

/// Programmatic expansion: dub-share-26…40 (15 Share) + dub-rent-31…50 (20 Rent).
abstract final class SampleListingsDublinExpansion {
  static List<Map<String, dynamic>> get shareItems => _share;
  static List<Map<String, dynamic>> get rentItems => _rent;

  static final List<Map<String, dynamic>> _share = [
    for (final spec in _shareSpecs) _buildShare(spec),
  ];

  static final List<Map<String, dynamic>> _rent = [
    for (final spec in _rentSpecs) _buildRent(spec),
  ];

  static Map<String, dynamic> _buildShare(_ShareSpec s) {
    final langs = s.languages;
    return DublinListingBuilder.build(
      id: s.id,
      title: s.title,
      price: s.price,
      location: s.location,
      type: 'Share',
      description: s.description,
      hostName: s.hostName,
      hostCity: s.hostCity,
      hostLanguage: langs.join(', '),
      hostMotherTongue: langs.first,
      foodPreference: s.food,
      roomType: s.roomType,
      furnishing: 'Furnished',
      occupantType: s.occupant,
      preferredTenantOccupant: s.preferredTenant ?? s.occupant,
      preferredTenantType: s.preferredTenant ?? s.occupant,
      languagesSpoken: langs,
      spokenLanguages: langs,
      genderPreference: s.gender ?? 'Any/Mixed',
      smokingAllowed: false,
      drinkingAllowed: s.drinking,
      proximityData: _proximity(s.transit, s.transitMinutes),
      availableFrom: s.availableFrom,
      hostTrustStage: s.trust,
    );
  }

  static Map<String, dynamic> _buildRent(_RentSpec s) {
    final langs = s.languages;
    return DublinListingBuilder.build(
      id: s.id,
      title: s.title,
      price: s.price,
      location: s.location,
      type: 'Rent',
      description: s.description,
      hostName: s.hostName,
      hostCity: s.hostCity,
      hostLanguage: langs.join(', '),
      hostMotherTongue: langs.first,
      foodPreference: s.food,
      furnishing: s.furnishing,
      bedrooms: s.bedrooms,
      bhk: s.bhk,
      occupantType: s.occupant,
      preferredTenantOccupant: s.preferredTenant,
      languagesSpoken: langs,
      spokenLanguages: langs,
      proximityData: _proximity(s.transit, s.transitMinutes),
      availableFrom: s.availableFrom,
      hostTrustStage: s.trust,
    );
  }

  static Map<String, dynamic>? _proximity(String kind, int minutes) {
    return switch (kind) {
      'luas' => DublinListingBuilder.luasProximity(minutes: minutes),
      'dart' => DublinListingBuilder.dartProximity(minutes: minutes),
      'bus' => DublinListingBuilder.busProximity(minutes: minutes),
      'multi' => DublinListingBuilder.multiModalProximity(
          luasMinutes: minutes,
          dartMinutes: minutes + 4,
          busMinutes: minutes + 2,
        ),
      _ => null,
    };
  }
}

