  static Listing _withCohorts({
    required String id,
    required String title,
    required ListingType type,
    String? subtitle,
    required List<Applicant> applicants,
  }) {
    var inviteReady = 0;
    var review = 0;
    var notSuitable = 0;
    for (final a in applicants) {
      if (a.recommendation == LandlordRecommendationState.notSuitable) {
        notSuitable++;
      } else if (a.verdict == DecisionVerdict.recommended) {
        inviteReady++;
      } else {
        review++;
      }
    }
    return Listing(
      id: id,
      title: title,
      subtitle: subtitle,
      type: type,
      applicantCount: applicants.length,
      inviteReadyCount: inviteReady,
      reviewCount: review,
      notSuitableCount: notSuitable,
      applicants: applicants,
    );
  }

